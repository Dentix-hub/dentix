export const CLINICAL_TOOTH_GEOMETRY = Object.freeze(GEOMETRY);

export function getClinicalToothGeometry(fdi) {
    const tooth = parseFdiTooth(fdi);
    const geometry = CLINICAL_TOOTH_GEOMETRY[tooth.templateKey];

    if (!geometry) {
        throw new Error(`Clinical geometry is not available for ${tooth.templateKey}`);
    }

    return Object.freeze({
        ...geometry,
        templateKey: tooth.templateKey,
        mirror: tooth.side === 'left',
        arch: tooth.arch,
        kind: tooth.kind,
    });
}

