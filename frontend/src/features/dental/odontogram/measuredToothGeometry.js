const quadrantOf = (fdi) => Math.floor(Number(fdi) / 10);
const positionOf = (fdi) => Number(fdi) % 10;

export function getMeasuredToothGeometry(fdi, isPediatric = false) {
    const quadrant = quadrantOf(fdi);
    const position = positionOf(fdi);
    const upper = quadrant === 1 || quadrant === 2 || quadrant === 5 || quadrant === 6;
    const leftSide = quadrant === 2 || quadrant === 3 || quadrant === 6 || quadrant === 7;

    let templateId;
    let scaleX = 1;
    let scaleY = 1;

    if (position <= 2) {
        templateId = 11;
        if (!upper) scaleX = 0.82;
        if (position === 2) scaleX *= 0.88;
    } else if (position === 3) {
        templateId = 13;
        if (!upper) scaleX = 0.9;
    } else if (position <= 5) {
        templateId = 14;
        if (!upper) {
            // Lower premolars are single rooted; compressing the measured upper-premolar
            // template keeps the clinical silhouette compact until the dedicated lower
            // measured template is introduced with the VNext surface engine.
            scaleX = 0.88;
        } else if (position === 5) {
            scaleX = 0.92;
        }
    } else if (upper) {
        templateId = 16;
        if (position === 7) scaleX = 0.94;
        if (position === 8) {
            scaleX = 0.87;
            scaleY = 0.94;
        }
    } else {
        templateId = 46;
        if (position === 7) scaleX = 0.94;
        if (position === 8) {
            scaleX = 0.88;
            scaleY = 0.94;
        }
    }

    if (isPediatric) {
        scaleX *= 0.86;
        scaleY *= 0.88;
    }

    return {
        ...MEASURED_TOOTH_TEMPLATES[templateId],
        templateId,
        upper,
        mirror: leftSide,
        scaleX,
        scaleY,
    };
}
