async def create_payment(
    db: AsyncSession, payment: schemas.PaymentCreate, tenant_id: int, doctor_id: int = None, commit: bool = True
):
    """
    Create a payment record.
    If doctor_id is not provided, it will be auto-assigned from the patient's most recent treatment.
    """
    patient = await get_patient(db, payment.patient_id, tenant_id)
    if not patient:
        return None

    payment_dict = payment.dict()

    # Auto-assign doctor_id if not provided - get from most recent treatment
    if not payment_dict.get("doctor_id") and not doctor_id:
        # Find most recent treatment for this patient
        stmt = (
            select(models.Treatment)
            .where(
                models.Treatment.patient_id == payment.patient_id,
                models.Treatment.doctor_id.isnot(None),
            )
            .order_by(models.Treatment.date.desc())
        )
        result = await db.execute(stmt)
        recent_treatment = result.scalars().first()
        if recent_treatment:
            doctor_id = recent_treatment.doctor_id

    # Set doctor_id if available
    if doctor_id and not payment_dict.get("doctor_id"):
        payment_dict["doctor_id"] = doctor_id

    # Ensure tenant_id is set
    if not payment_dict.get("tenant_id"):
        payment_dict["tenant_id"] = tenant_id

    db_payment = models.Payment(**payment_dict)
    db.add(db_payment)
    if commit:
        await db.commit()
        # REGRESSION (2026-06-19): Eager-load patient relationship on the
        # returned Payment. schemas.Payment declares patient_name as
        # an Optional[str] from_attributes field — the underlying
        # @property accesses self.patient.name, which lazy-loads after
        # the route returns and triggers MissingGreenlet during
        # response serialization.
        await db.refresh(
            db_payment,
            attribute_names=["patient"],
        )
        # Touch patient.name while greenlet context is still alive so the
        # @property has a fully-loaded value to return later.
        _ = db_payment.patient.name if db_payment.patient else None
    else:
        await db.flush()
        await db.refresh(
            db_payment,
            attribute_names=["patient"],
        )
        _ = db_payment.patient.name if db_payment.patient else None
    invalidate_dashboard_cache(tenant_id)
    asyncio.create_task(
        precompute_dashboard_cache(tenant_id=tenant_id, db=db)
    )
    return db_payment


