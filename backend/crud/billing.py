async def get_financial_stats(db: AsyncSession, tenant_id: int, doctor_id: int = None):
    """
    Get financial statistics for a tenant.

    Uses 3 batch aggregation queries (CASE WHEN) instead of 9 individual ones:
      Query 1 — Treatment revenue (total cost, total discount, today net revenue)
      Query 2 — Payment totals (all-time and today)
      Query 3 — Lab costs + Expenses (all-time and today)
    """
    today_start = datetime.now(timezone.utc).replace(hour=0, minute=0, second=0, microsecond=0)

    # ------------------------------------------------------------------
    # Query 1: Treatment revenue — total cost, total discounts, today net
    # ------------------------------------------------------------------
    treatment_base = (
        select(
            func.sum(models.Treatment.cost).label("total_cost"),
            func.sum(models.Treatment.discount).label("total_discount"),
            func.sum(
                case(
                    (models.Treatment.date >= today_start,
                     models.Treatment.cost - models.Treatment.discount),
                    else_=0,
                )
            ).label("today_revenue"),
        )
        .join(models.Patient)
        .where(
            models.Patient.tenant_id == tenant_id,
            models.Patient.is_deleted == False,  # noqa: E712
        )
    )
    if doctor_id:
        treatment_base = treatment_base.where(models.Treatment.doctor_id == doctor_id)

    t_row = (await db.execute(treatment_base)).first()
    total_treatments = float(t_row.total_cost or 0.0)
    total_discounts  = float(t_row.total_discount or 0.0)
    total_revenue    = total_treatments - total_discounts
    today_revenue    = float(t_row.today_revenue or 0.0)

    # ------------------------------------------------------------------
    # Query 2: Payment totals — all-time and today
    # ------------------------------------------------------------------
    payment_base = (
        select(
            func.sum(models.Payment.amount).label("total_received"),
            func.sum(
                case(
                    (models.Payment.date >= today_start, models.Payment.amount),
                    else_=0,
                )
            ).label("today_received"),
        )
        .join(models.Patient)
        .where(
            models.Patient.tenant_id == tenant_id,
            models.Patient.is_deleted == False,  # noqa: E712
        )
    )
    if doctor_id:
        payment_base = payment_base.where(models.Payment.doctor_id == doctor_id)

    p_row = (await db.execute(payment_base)).first()
    total_received = float(p_row.total_received or 0.0)
    today_received = float(p_row.today_received or 0.0)

    # ------------------------------------------------------------------
    # Query 3: Lab costs + Expenses — all-time and today
    # (Expenses are skipped when filtering by doctor_id; lab orders join Patient)
    # ------------------------------------------------------------------
    lab_base = (
        select(
            func.sum(models.LabOrder.cost).label("total_lab"),
            func.sum(
                case(
                    (models.LabOrder.order_date >= today_start, models.LabOrder.cost),
                    else_=0,
                )
            ).label("today_lab"),
        )
        .join(models.Patient)
        .where(
            models.LabOrder.tenant_id == tenant_id,
            models.Patient.is_deleted == False,  # noqa: E712
        )
    )
    if doctor_id:
        lab_base = lab_base.where(models.LabOrder.doctor_id == doctor_id)

    l_row = (await db.execute(lab_base)).first()
    total_lab_costs = float(l_row.total_lab or 0.0)
    today_lab_costs = float(l_row.today_lab or 0.0)

    if doctor_id:
        # Expenses are not doctor-specific; skip when filtering by doctor
        total_expenses = 0.0
        today_expenses = 0.0
    else:
        exp_base = select(
            func.sum(models.Expense.cost).label("total_expenses"),
            func.sum(
                case(
                    (models.Expense.date == date.today(), models.Expense.cost),
                    else_=0,
                )
            ).label("today_expenses"),
        ).where(models.Expense.tenant_id == tenant_id)

        # Expenses query is folded into Query 3 logically but executed as a
        # lightweight single-table aggregate — still just 1 round-trip.
        e_row = (await db.execute(exp_base)).first()
        total_expenses = float(e_row.total_expenses or 0.0)
        today_expenses = float(e_row.today_expenses or 0.0)

    # ------------------------------------------------------------------
    # Derived aggregates
    # ------------------------------------------------------------------
    outstanding       = total_revenue - total_received
    today_outstanding = max(0, today_revenue - today_received)
    net_profit        = total_received - total_expenses - total_lab_costs

    return {
        "total_revenue":    total_revenue,
        "total_received":   total_received,
        "outstanding":      outstanding if outstanding > 0 else 0,
        "total_expenses":   total_expenses + total_lab_costs,
        "net_profit":       net_profit,
        "monthly_revenue":  0.0,
        "today_revenue":    today_revenue,
        "today_received":   today_received,
        "today_outstanding": today_outstanding,
        "today_expenses":   today_expenses + today_lab_costs,
    }


async def get_dashboard_stats(db: AsyncSession, tenant_id: int, doctor_id: int = None):
    # Reuse financial stats logic
    fin_stats = await get_financial_stats(db, tenant_id, doctor_id)

    patients_stmt = select(func.count(models.Patient.id)).where(
        models.Patient.tenant_id == tenant_id,
        models.Patient.is_deleted == False,  # noqa: E712
    )
    if doctor_id:
        patients_stmt = patients_stmt.where(
            models.Patient.assigned_doctor_id == doctor_id
        )

    result = await db.execute(patients_stmt)
    total_patients = result.scalar() or 0

    today_start = datetime.now(timezone.utc).replace(hour=0, minute=0, second=0, microsecond=0)

    # 2. New Patients Today
    new_patients_stmt = select(func.count(models.Patient.id)).where(
        models.Patient.tenant_id == tenant_id,
        models.Patient.is_deleted == False,  # noqa: E712
        func.date(models.Patient.created_at) == func.date(today_start),
    )

    if doctor_id:
        new_patients_stmt = new_patients_stmt.where(
            models.Patient.assigned_doctor_id == doctor_id
        )

    result = await db.execute(new_patients_stmt)
    new_patients_today = result.scalar() or 0

    # 3. Today's Appointments Count
    appointments_stmt = (
        select(func.count(models.Appointment.id))
        .join(models.Patient)
        .where(
            models.Patient.tenant_id == tenant_id,
            models.Patient.is_deleted == False,  # noqa: E712
            models.Appointment.is_deleted == False,  # noqa: E712
            models.Appointment.status != "Cancelled",  # FIX: Exclude cancelled
            func.date(models.Appointment.date_time) == func.date(today_start),
        )
    )

    if doctor_id:
        appointments_stmt = appointments_stmt.where(
            models.Appointment.doctor_id == doctor_id
        )

    result = await db.execute(appointments_stmt)
    total_appointments_today = result.scalar() or 0

    # 4. Revenue Chart (Last 7 Days)
    chart_start = today_start - timedelta(days=6)
    chart_end   = today_start + timedelta(days=1)

    _rev_stmt = (
        select(
            cast(models.Payment.date, SADate).label("day"),
            func.sum(models.Payment.amount).label("total"),
        )
        .join(models.Patient)
        .where(
            models.Patient.tenant_id == tenant_id,
            models.Patient.is_deleted == False,  # noqa: E712
            models.Payment.date >= chart_start,
            models.Payment.date < chart_end,
        )
        .group_by(cast(models.Payment.date, SADate))
    )
    if doctor_id:
        _rev_stmt = _rev_stmt.where(models.Payment.doctor_id == doctor_id)

    _rev_result = await db.execute(_rev_stmt)
    _rev_by_day = {row.day: float(row.total) for row in _rev_result.fetchall()}

    chart_data = [
        {
            "name": (today_start - timedelta(days=i)).strftime("%Y-%m-%d"),
            "revenue": _rev_by_day.get((today_start - timedelta(days=i)).date(), 0.0),
        }
        for i in range(6, -1, -1)
    ]

    return {
        **fin_stats,
        "total_patients": total_patients,
        "new_patients_today": new_patients_today,
        "total_appointments_today": total_appointments_today,
        "revenue_chart": chart_data,
    }
