# --- Treatment CRUD ---
async def create_treatment(
    db: AsyncSession,
    treatment: schemas.TreatmentCreate,
    tenant_id: int = None,
    doctor_id: int = None,
    price_list_id: int = None,
    unit_price: float = None,
    price_snapshot: str = None,
    commit: bool = True,
):
    """
    Create a treatment record.
    If doctor_id or tenant_id are not provided in the schema, they will be auto-filled from parameters.
    """
    treatment_dict = treatment.dict()

    # Remove fields that are not part of the Treatment model
    treatment_dict.pop("consumedMaterials", None)
    treatment_dict.pop("skip_stock_check", None)

    # Auto-fill doctor_id if not provided
    if not treatment_dict.get("doctor_id") and doctor_id:
        treatment_dict["doctor_id"] = doctor_id

    # Auto-fill tenant_id if not provided
    if not treatment_dict.get("tenant_id") and tenant_id:
        treatment_dict["tenant_id"] = tenant_id

    db_treatment = models.Treatment(**treatment_dict)

    if price_list_id:
        db_treatment.price_list_id = price_list_id
    if unit_price is not None:
        db_treatment.unit_price = unit_price
    if price_snapshot:
        db_treatment.price_snapshot = price_snapshot

    db.add(db_treatment)
    if commit:
        await db.commit()
        # REGRESSION (2026-06-19): Eager-load treatment_sessions before
        # returning the ORM object, otherwise Pydantic's response
        # serialization of schemas.Treatment.treatment_sessions
        # (Optional[list[TreatmentSession]]) will lazy-load outside the
        # greenlet context and raise MissingGreenlet.
        await db.refresh(
            db_treatment,
            attribute_names=["treatment_sessions"],
        )
    else:
        await db.flush()
        await db.refresh(
            db_treatment,
            attribute_names=["treatment_sessions"],
        )
    return db_treatment


async def get_doctor_revenue(
    db: AsyncSession, doctor_id: int, start_date: datetime, end_date: datetime
):
    # Calculate total revenue generated by a doctor
    stmt = (
        select(
            func.sum(models.Treatment.cost - models.Treatment.discount).label("revenue"),
            func.count(models.Treatment.id).label("treatment_count"),
        )
        .join(models.Patient, models.Treatment.patient_id == models.Patient.id)
        .where(
            models.Treatment.doctor_id == doctor_id,
            models.Treatment.date >= start_date,
            models.Treatment.date <= end_date,
            models.Patient.is_deleted == False,  # noqa: E712
        )
    )
    result = await db.execute(stmt)
    row = result.first()
    return {
        "revenue": row.revenue or 0.0 if row else 0.0,
        "treatment_count": row.treatment_count or 0 if row else 0,
    }


async def get_treatments(db: AsyncSession, patient_id: int, tenant_id: int):
    # 1. Fetch treatments
    stmt = (
        select(models.Treatment)
        .join(models.Patient)
        .where(
            models.Treatment.patient_id == patient_id,
            models.Patient.tenant_id == tenant_id,
            models.Patient.is_deleted == False,  # noqa: E712
        )
        .options(selectinload(models.Treatment.treatment_sessions))
    )
    result = await db.execute(stmt)
    treatments = result.scalars().all()

    if not treatments:
        return []

    # 2. Reconstruct Consumed Materials from Stock Movements
    # Collect IDs for batch query
    treatment_ids = [str(t.id) for t in treatments]
    reference_ids = [f"TREATMENT:{tid}" for tid in treatment_ids]

    if not reference_ids:
        return treatments

    try:
        # Fetch all movements linked to these treatments
        stmt_m = (
            select(models.StockMovement)
            .where(models.StockMovement.reference_id.in_(reference_ids))
            .join(models.StockItem)
            .join(models.Batch)
            .join(models.Material)
            .options(
                joinedload(models.StockMovement.stock_item)
                .joinedload(models.StockItem.batch)
                .joinedload(models.Batch.material)
            )
        )
        result_m = await db.execute(stmt_m)
        movements = result_m.scalars().all()

        # Map movements to treatment_id
        movements_map = {}  # treatment_id -> { material_id: quantity }

        for m in movements:
            try:
                # Parse reference_id "TREATMENT:123"
                parts = m.reference_id.split(":")
                if len(parts) < 2:
                    continue

                t_id = int(parts[1])

                # Use batch material
                mat_id = m.stock_item.batch.material_id
                qty = abs(m.change_amount)

                if t_id not in movements_map:
                    movements_map[t_id] = {}

                # Aggregate quantity for same material
                if mat_id in movements_map[t_id]:
                    movements_map[t_id][mat_id] += qty
                else:
                    movements_map[t_id][mat_id] = qty

            except Exception:
                continue

        # Attach list to treatment objects
        # We need to construct objects compatible with schemas.ConsumedMaterialItem
        # Pydantic will serialize generic dicts/objects if attributes match
        from backend.schemas.clinical import ConsumedMaterialItem

        for t in treatments:
            if t.id in movements_map:
                # Convert dict {mat_id: qty} to list of objects
                items = []
                for mat_id, qty in movements_map[t.id].items():
                    items.append(ConsumedMaterialItem(material_id=mat_id, quantity=qty))

                # Create a temporary attribute on the ORM object
                # This works because Pydantic `from_attributes=True` reads it
                t.consumedMaterials = items
            else:
                t.consumedMaterials = []

    except Exception as e:
        logger.error("Error reconstructing consumed materials: %s", e)

    return treatments


